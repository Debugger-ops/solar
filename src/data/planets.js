export function factsFor(planet) {
  const years = planet.periodDays / 365.25
  const facts = []
  if (planet.dwarf) facts.push(['Classification', 'Dwarf planet'])
  facts.push(
    ['Distance from sun', `${planet.distanceAU} AU`],
    ['Orbital period', years >= 1 ? `${years.toFixed(1)} years` : `${planet.periodDays.toFixed(0)} days`],
    ['Orbit eccentricity', planet.ecc.toFixed(3)],
    ['Orbit inclination', `${planet.inclDeg.toFixed(2)}°`],
    ['Radius', `${planet.earthRadii.toFixed(2)} × Earth`],
    ['Mass', `${planet.massEarths < 1 ? planet.massEarths.toFixed(3) : planet.massEarths.toFixed(1)} × Earth`],
    ['Surface gravity', `${planet.gravityG.toFixed(2)} g`],
    ['Day length', planet.dayLength],
    ['Avg. surface temp.', planet.avgTempC],
    ['Moons', String(planet.moons)],
    ['Atmosphere', planet.atmosphere],
  )
  return facts
}

export function moonFactsFor(moon, parent) {
  return [
    ['Orbits', parent.name],
    ['Tidal lock', moon.tidalLocked ? `Yes - same face always faces ${parent.name}` : 'No'],
    ['Distance from ' + parent.name, `${moon.distanceKm.toLocaleString()} km`],
    [
      'Orbital period',
      moon.periodDays < 1 ? `${(moon.periodDays * 24).toFixed(1)} hours` : `${moon.periodDays.toFixed(2)} days`,
    ],
    ['Radius', `${moon.radiusKm.toLocaleString()} km`],
  ]
}

// Looks a selected name up across the sun, the planets, and every planet's
// moons, so the info card and camera rig don't each need their own copy of
// this search.
export function findBody(name) {
  if (name === 'Sun') return { kind: 'sun', body: SUN }
  const planet = PLANETS.find((p) => p.name === name)
  if (planet) return { kind: 'planet', body: planet }
  for (const p of PLANETS) {
    const moon = p.moonBodies?.find((m) => m.name === name)
    if (moon) return { kind: 'moon', body: moon, parent: p }
  }
  return null
}
